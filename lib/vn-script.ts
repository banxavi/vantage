export function layoutScript(text: string) {
  const gap = 6
  let x = 2
  let spaced = false
  const parts: { d: string; x: number }[] = []
  for (const ch of text) {
    if (ch === ' ') {
      x += 36
      spaced = false
      continue
    }
    const glyph = glyphs[ch]
    if (!glyph) continue
    if (spaced) x += gap
    parts.push({ d: glyph.d, x })
    x += glyph.w
    spaced = true
  }
  return { parts, width: Math.max(16, x + 2) }
}
